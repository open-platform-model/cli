// Package config provides configuration loading and management.
package config

import "fmt"

// DefaultRegistry is the default CUE_REGISTRY value used when initializing a
// fresh OPM configuration (the `config.registry` value in the generated
// config.cue).
const DefaultRegistry = "testing.opmodel.dev=ghcr.io/open-platform-model,opmodel.dev=ghcr.io/open-platform-model,registry.cue.works"

// DefaultConfigTemplate is the embedded template for ~/.opm/config.cue.
// Scalar data only — no CUE imports, no providers (enhancement 0006 D39).
var DefaultConfigTemplate = fmt.Sprintf(`// OPM CLI Configuration
// Generated by: opm config init
// Documentation: https://opmodel.dev/docs/cli/config
package config

config: {
	// registry is the default registry for CUE module resolution.
	// Override with --registry flag or OPM_REGISTRY env var.
	registry: %q

	kubernetes: {
		// kubeconfig is the path to the kubeconfig file.
		// Override with --kubeconfig flag or OPM_KUBECONFIG env var.
		kubeconfig: "~/.kube/config"

		// context is the Kubernetes context to use.
		// Override with --context flag or OPM_CONTEXT env var.
		// Default: current-context from kubeconfig
		context?: string

		// namespace is the default namespace for operations.
		// Override with --namespace flag or OPM_NAMESPACE env var.
		namespace: "default"
	}

	// log controls logging behavior.
	log: {
		// timestamps controls whether timestamps are shown in log output.
		// Override with --timestamps flag.
		timestamps: true

		// kubernetes controls Kubernetes-related log behavior.
		kubernetes: {
			// apiWarnings controls how K8s API deprecation warnings are displayed.
			// "warn"     - Show as WARN in log output
			// "debug"    - Only show with --verbose (default)
			// "suppress" - Drop entirely
			apiWarnings: "debug"
		}
	}
}
`, DefaultRegistry)

// DefaultCatalogPaths are the major-suffixed CUE module paths of the two
// first-party catalogs: the abstraction catalog and the raw Kubernetes
// passthrough catalog extracted from it (enhancement 0010 D47, catalog_opm's
// k8s@v1 split). The generated default platform subscribes to both, so each
// path is spelled exactly once here.
var DefaultCatalogPaths = []string{
	"opmodel.dev/catalogs/opm@v2",
	"opmodel.dev/catalogs/k8s@v1",
}

// DefaultCatalogPath is the entry `opm operator install` resolves a published
// version of when it seeds a single-catalog cluster Platform. Derived from
// DefaultCatalogPaths rather than a second literal: install has no per-catalog
// resolution (that is tracked separately against operator-install-platform),
// so it keeps naming exactly one catalog — the abstraction catalog.
var DefaultCatalogPath = DefaultCatalogPaths[0]

// DefaultPlatformTemplate is the embedded template for ~/.opm/platform.cue —
// the local default platform (enhancement 0006 D39, D21 precedence source 3).
// Data-only projection of the Platform CR spec: wrapped in
// apiVersion/kind/metadata this document IS the cluster singleton Platform.
//
// The seeded catalog version pins are load-bearing and hand-bumped as catalog
// releases ship (`opm config init` is normatively offline — it cannot
// resolve "latest"). Both pins are mirrored in the same commit across:
// hack/platform.cue, hack/kind-platform.yaml (kind dev flow), and the
// operator's config/samples Platform. An immutable published tag never
// dangles, so the drift mode of a stale pin is "old but resolvable".
var DefaultPlatformTemplate = fmt.Sprintf(`// OPM local default platform
// Generated by: opm config init
// Used when no --platform flag is given and no cluster Platform CR is
// readable. Data only — CUE imports are not allowed in this file.
// Documentation: https://opmodel.dev/docs/cli/config

// name is the platform name. "cluster" matches the in-cluster singleton
// this file seeds on first apply against an empty cluster.
name: "cluster"

// type is an informational discriminator; it does not affect matching.
type: "kubernetes"

// registry subscribes this platform to catalogs by major-suffixed CUE
// module path: the abstraction catalog for portable contracts, and the raw
// Kubernetes passthrough catalog as the escape hatch when an abstraction
// doesn't fit. Each subscription pins exactly one published catalog build;
// bump the versions by hand as catalog releases ship.
registry: {
	%q: {
		version: "2.0.0-alpha.6"
	}
	%q: {
		version: "1.0.0-alpha.1"
	}
}
`, DefaultCatalogPaths[0], DefaultCatalogPaths[1])
