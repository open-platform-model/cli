// Package crds holds the CustomResourceDefinitions of the controller module
// version the cli pins, as that version renders them for the controller's
// instance. task controller:pin writes the manifests (one file per CRD, see
// Manifest); `opm controller install --crds-only` applies them without a
// registry.
package crds

import (
	"bytes"
	"embed"
	"fmt"
	"io/fs"
	"path"
	"strings"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"sigs.k8s.io/yaml"
)

// Header opens every manifest file.
const Header = "# Code generated by task controller:pin; DO NOT EDIT.\n"

// Kind is the only kind a manifest holds.
const Kind = "CustomResourceDefinition"

//go:embed *.yaml
var manifests embed.FS

// Objects returns the embedded CRDs in file-name order, each a fresh copy.
func Objects() ([]*unstructured.Unstructured, error) {
	return Read(manifests)
}

// Read parses every *.yaml file at the root of fsys as one CRD manifest, in
// file-name order.
func Read(fsys fs.FS) ([]*unstructured.Unstructured, error) {
	entries, err := fs.ReadDir(fsys, ".")
	if err != nil {
		return nil, err
	}
	var objs []*unstructured.Unstructured
	for _, e := range entries {
		if e.IsDir() || path.Ext(e.Name()) != ".yaml" {
			continue
		}
		data, err := fs.ReadFile(fsys, e.Name())
		if err != nil {
			return nil, err
		}
		obj, err := Parse(data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", e.Name(), err)
		}
		if want := FileName(obj); want != e.Name() {
			return nil, fmt.Errorf("%s: holds CRD %s, which belongs in %s", e.Name(), obj.GetName(), want)
		}
		objs = append(objs, obj)
	}
	if len(objs) == 0 {
		return nil, fmt.Errorf("no CRD manifests")
	}
	return objs, nil
}

// Parse reads one manifest.
func Parse(data []byte) (*unstructured.Unstructured, error) {
	js, err := yaml.YAMLToJSON(data)
	if err != nil {
		return nil, err
	}
	obj := &unstructured.Unstructured{}
	if err := obj.UnmarshalJSON(js); err != nil {
		return nil, err
	}
	if obj.GetKind() != Kind || obj.GetName() == "" {
		return nil, fmt.Errorf("not a named %s (kind %q, name %q)", Kind, obj.GetKind(), obj.GetName())
	}
	return obj, nil
}

// FileName is the manifest file of a CRD: its name plus ".yaml".
func FileName(obj *unstructured.Unstructured) string {
	return obj.GetName() + ".yaml"
}

// Manifest is the file content for one CRD: Header, then the object as YAML
// with sorted keys, so the same object always yields the same bytes.
func Manifest(obj *unstructured.Unstructured) ([]byte, error) {
	if obj.GetKind() != Kind || obj.GetName() == "" || strings.ContainsAny(obj.GetName(), "/\\") {
		return nil, fmt.Errorf("not a named %s (kind %q, name %q)", Kind, obj.GetKind(), obj.GetName())
	}
	body, err := yaml.Marshal(obj.Object)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(Header)
	b.Write(body)
	return b.Bytes(), nil
}
